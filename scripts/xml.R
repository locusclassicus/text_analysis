# Глава учебника: https://locusclassicus.github.io/text_analysis/xml.html

library(tidyverse)
library(xml2)

# ============================================================
# TEI XML В R: ШПАРГАЛКА К УРОКУ
#
# XML — язык разметки для хранения структурированных данных.
# Документ XML устроен как дерево:
#
# - один корневой элемент;
# - внутри него находятся дочерние элементы;
# - элементы могут содержать текст и атрибуты;
# - каждый открывающий тег должен иметь закрывающий тег.
#
# Пакет xml2 позволяет читать XML, перемещаться по дереву
# и извлекать нужные элементы, тексты и атрибуты.
# ============================================================


# ------------------------------------------------------------
# 1. СОЗДАЁМ ПРОСТОЙ XML-ДОКУМЕНТ
#
# XML можно прочитать не только из файла, но и прямо из строки.
#
# В примере ниже:
#
# <recipe> — корневой элемент;
# <title>, <composition>, <instructions> — его дети;
# <ingredient> и <step> — элементы более глубокого уровня;
# name, amount, unit — атрибуты элементов.
# ------------------------------------------------------------

string_xml <- '<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE recipe>
<recipe name="хлеб" preptime="5min" cooktime="180min">
   <title>
      Простой хлеб
   </title>
   <composition>
      <ingredient amount="3" unit="стакан">Мука</ingredient>
      <ingredient amount="0.25" unit="грамм">Дрожжи</ingredient>
      <ingredient amount="1.5" unit="стакан">Тёплая вода</ingredient>
   </composition>
   <instructions>
     <step>
        Смешать все ингредиенты и тщательно замесить. 
     </step>
     <step>
        Закрыть тканью и оставить на один час в тёплом помещении. 
     </step>
     <step>
        Замесить ещё раз, положить на противень и поставить в духовку.
     </step>
   </instructions>
</recipe>'


# ------------------------------------------------------------
# 2. ЧТЕНИЕ XML
#
# read_xml() превращает строку или файл в XML-документ.
#
# Полученный объект сохраняет древовидную структуру исходного
# документа. Это ещё не таблица и не обычный текст.
# ------------------------------------------------------------

doc <- read_xml(string_xml)

class(doc)


# ------------------------------------------------------------
# 3. КОРНЕВОЙ ЭЛЕМЕНТ
#
# xml_root() возвращает корневой элемент документа.
#
# В нашем примере корневой элемент — <recipe>.
# Внутри него находятся все остальные элементы.
# ------------------------------------------------------------

rootnode <- xml_root(doc)

rootnode


# ------------------------------------------------------------
# 4. ДОЧЕРНИЕ ЭЛЕМЕНТЫ
#
# xml_children() возвращает непосредственных детей узла.
#
# Важно: функция не ищет элементы на всех уровнях дерева.
# Она показывает только следующий уровень вложенности.
# ------------------------------------------------------------

children <- xml_children(rootnode)
children


# ------------------------------------------------------------
# xml_name() возвращает имена XML-элементов.
#
# Здесь мы узнаём, как называются непосредственные дети
# корневого элемента <recipe>.
# ------------------------------------------------------------

xml_name(children)


# ------------------------------------------------------------
# 5. ПОИСК ПЕРВОГО ЭЛЕМЕНТА
#
# xml_find_first() возвращает первый узел,
# соответствующий запросу.
#
# Здесь ищем элемент <composition> внутри <recipe>.
# ------------------------------------------------------------

composition_node <- xml_find_first(rootnode, "composition")
composition_node


# ------------------------------------------------------------
# Узел можно выбрать и по его позиции.
#
# [[3]] означает третий элемент среди детей rootnode.
#
# Такой способ допустим, но обычно менее надёжен:
# если структура XML изменится, нужный элемент может оказаться
# на другой позиции.
# ------------------------------------------------------------

instructions_node <- xml_children(rootnode)[[3]]
instructions_node


# ------------------------------------------------------------
# 6. ИЗВЛЕЧЕНИЕ ТЕКСТА
#
# xml_text() возвращает текстовое содержимое узла.
#
# Сначала получаем детей <composition>,
# затем извлекаем текст каждого дочернего элемента.
# ------------------------------------------------------------

composition_node |>
  xml_children() |>
  xml_text()



# ------------------------------------------------------------
# 7. АТРИБУТЫ ЭЛЕМЕНТОВ
#
# xml_attrs() возвращает сразу все атрибуты каждого узла.
#
# У ингредиентов есть два атрибута:
#
# amount — количество;
# unit   — единица измерения.
# ------------------------------------------------------------

composition_node |>
  xml_children() |>
  xml_attrs()


# ------------------------------------------------------------
# xml_attr() извлекает один конкретный атрибут.
#
# Вторым аргументом указываем имя атрибута.
# ------------------------------------------------------------

composition_node |>
  xml_children() |>
  xml_attr("unit")


composition_node |>
  xml_children() |>
  xml_attr("amount")


# ------------------------------------------------------------
# 8. XPATH
#
# XPath — язык запросов к XML-дереву.
#
# Он позволяет описать путь до нужных элементов.
#
# Основные обозначения:
#
# /   — перейти к непосредственному ребёнку;
# //  — искать на любой глубине;
# @   — обратиться к атрибуту;
# []  — задать условие;
# .   — начать поиск от текущего узла.
# ------------------------------------------------------------


# ------------------------------------------------------------
# АБСОЛЮТНЫЙ ПУТЬ
#
# Запрос начинается от корневого элемента <recipe>.
#
# /recipe//composition//ingredient
#
# Находим <recipe>, затем внутри него <composition>,
# а затем все вложенные элементы <ingredient>.
# ------------------------------------------------------------

xml_find_all(
  rootnode,
  "/recipe//composition//ingredient"
)


# ------------------------------------------------------------
# ОТНОСИТЕЛЬНЫЙ ПУТЬ
#
# Запрос начинается от текущего узла rootnode.
#
# Двойной слеш означает поиск на любой глубине.
# ------------------------------------------------------------

xml_find_all(
  rootnode,
  "//composition//ingredient"
)


# ------------------------------------------------------------
# ОТБОР ПО АТРИБУТУ
#
# [@unit='стакан'] означает:
#
# выбрать только те элементы <ingredient>,
# у которых атрибут unit равен "стакан".
# ------------------------------------------------------------

xml_find_all(
  rootnode,
  "//composition//ingredient[@unit='стакан']"
)


# ------------------------------------------------------------
# 9. ПРЕОБРАЗОВАНИЕ XML В ТАБЛИЦУ
#
# Обычно цель анализа — превратить древовидный XML
# в прямоугольную таблицу.
#
# Для этого отдельно извлекаем:
#
# - название рецепта;
# - названия ингредиентов;
# - единицы измерения;
# - количество.
# ------------------------------------------------------------

title <- rootnode |>
  xml_find_first("title") |>
  xml_text() |>
  trimws()

title


ingredient_nodes <- rootnode |>
  xml_find_all("//composition//ingredient")

ingredient_nodes


# ------------------------------------------------------------
# Каждый столбец тиббла создаётся из вектора одинаковой длины.
#
# Название рецепта состоит из одного значения,
# но tibble автоматически повторит его для каждой строки.
#
# amount пока остаётся текстовым столбцом,
# потому что значения XML-атрибутов всегда извлекаются
# как строки.
# ------------------------------------------------------------

recipe_df <- tibble(
  title = title,
  ingredient = ingredient_nodes |>
    xml_text() |>
    trimws(),
  unit = ingredient_nodes |>
    xml_attr("unit"),
  amount = ingredient_nodes |>
    xml_attr("amount")
)

recipe_df


# ------------------------------------------------------------
# При необходимости текстовый столбец можно преобразовать
# в числовой при помощи as.numeric().
# ------------------------------------------------------------

recipe_df <- recipe_df |>
  mutate(
    amount = as.numeric(amount)
  )

recipe_df


# ============================================================
# TEI XML
#
# TEI — стандарт разметки текстов, основанный на XML.
#
# Типичная структура TEI-документа:
#
# <TEI>
#   <teiHeader>...</teiHeader>
#   <text>...</text>
# </TEI>
#
# teiHeader содержит метаданные.
# text содержит сам текст произведения.
# ============================================================


# ------------------------------------------------------------
# 10. ОСНОВНЫЕ ЭЛЕМЕНТЫ TEI
#
# <teiHeader> — метаданные документа;
# <text>      — текст целиком;
# <body>      — основная часть текста;
# <div>       — глава, часть, действие, сцена;
# <p>         — абзац;
# <l>         — стихотворная строка;
# <lg>        — группа строк или строфа;
# <sp>        — речь персонажа;
# <speaker>   — имя говорящего;
# <stage>     — ремарка.
# ------------------------------------------------------------


# ------------------------------------------------------------
# ВАРИАНТЫ И ИСПРАВЛЕНИЯ
#
# <choice> объединяет альтернативные варианты текста.
# <orig> — оригинальное написание;
# <reg>  — нормализованное написание;
# <sic>  — ошибочное или необычное чтение источника;
# <corr> — исправленный вариант.
#
# Пример:
#
# <choice>
#   <sic>вихремъ</sic>
#   <corr resp="#editor1">верхомъ</corr>
# </choice>
#
# Атрибут resp указывает, кто внёс исправление.
# ------------------------------------------------------------


# ============================================================
# КЕЙС: «ГОРЕ ОТ УМА»
#
# Задача:
#
# 1. скачать TEI XML пьесы;
# 2. найти все стихотворные строки;
# 3. для каждой строки определить говорящего;
# 4. определить действие и явление;
# 5. собрать всё в таблицу.
# ============================================================


# ------------------------------------------------------------
# 11. СКАЧИВАНИЕ XML
#
# download_xml() скачивает XML по ссылке
# и сохраняет его в локальный файл.
# ------------------------------------------------------------

url <- "https://raw.githubusercontent.com/dracor-org/rusdracor/main/tei/griboyedov-gore-ot-uma.xml"
download_xml(url, file = "griboedov.xml")


# ------------------------------------------------------------
# Читаем скачанный файл.
#
# Здесь указываем путь к файлу относительно рабочей папки.
# ------------------------------------------------------------

doc <- read_xml("files/griboedov.xml")


# ------------------------------------------------------------
# 12. ПРОСТРАНСТВО ИМЁН
#
# В TEI элементы принадлежат пространству имён.
#
# Пространство имён можно представить как «фамилию» тега:
# оно помогает отличать одинаково названные элементы,
# принадлежащие разным стандартам.
#
# xml_ns() показывает пространства имён документа.
# ------------------------------------------------------------

ns <- xml_ns(doc)

ns


# ------------------------------------------------------------
# По умолчанию пространство имён может называться d1.
#
# Для удобства переименуем его в tei.
#
# После этого в XPath-запросах будем писать:
#
# tei:l
# tei:sp
# tei:speaker
# tei:div
# ------------------------------------------------------------

ns <- xml_ns_rename(
  xml_ns(doc),
  d1 = "tei"
)

ns


# ------------------------------------------------------------
# 13. НАХОДИМ ВСЕ СТИХОТВОРНЫЕ СТРОКИ
#
# //tei:l означает:
#
# найти все элементы <l> пространства имён TEI
# на любой глубине документа.
# ------------------------------------------------------------

line_nodes <- xml_find_all(
  doc,
  "//tei:l",
  ns
)

line_nodes

# ------------------------------------------------------------
# РАЗДЕЛЁННЫЕ СТИХОТВОРНЫЕ СТРОКИ
#
# Атрибут part показывает, что элемент <l> содержит
# не целую стихотворную строку, а только её часть.
#
# Возможные значения:
#
# part = "I" — начало строки (Initial);
# part = "M" — середина строки (Middle);
# part = "F" — конец строки (Final).
#
# Такие элементы встречаются в пьесах, когда одну
# стихотворную строку произносят несколько персонажей.
#
# Например:
#
# <l part="I">Который час?</l>
# <l part="F">Все в доме поднялось.</l>
#
# Эти два элемента составляют одну полную стихотворную строку:
#
# Который час? Все в доме поднялось.
#
# При анализе реплик каждый элемент <l> можно учитывать
# отдельно. При анализе стихотворных строк части I, M и F
# необходимо объединять.
# ------------------------------------------------------------


# ------------------------------------------------------------
# Извлекаем текст каждой строки.
#
# Получаем вектор, в котором один элемент соответствует
# одной строке пьесы.
# ------------------------------------------------------------

line_text <- line_nodes |>
  xml_text() |>
  trimws()

head(line_text)


# ------------------------------------------------------------
# 14. ОПРЕДЕЛЯЕМ ГОВОРЯЩЕГО
#
# Строка <l> находится внутри речи <sp>.
#
# Имя персонажа хранится в соседнем элементе <speaker>.
#
# Поэтому для каждой строки нужно:
#
# 1. подняться к предку <sp>;
# 2. внутри него найти <speaker>;
# 3. извлечь текст.
#
# ancestor::tei:sp означает:
# найти предка текущего узла с тегом <sp>.
# ------------------------------------------------------------

speakers <- line_nodes |>
  xml_find_first(
    "ancestor::tei:sp/tei:speaker",
    ns = ns
  ) |>
  xml_text() |>
  trimws()

head(speakers)


# ------------------------------------------------------------
# Почему здесь используется xml_find_first(), а не
# xml_find_all()?
#
# Для каждой строки нужен ровно один говорящий.
# xml_find_first() сохраняет соответствие:
#
# одна строка <l> — один элемент результата.
#
# Благодаря этому длина speakers совпадает
# с длиной line_text.
# ------------------------------------------------------------

length(line_text)

length(speakers)


# ------------------------------------------------------------
# 15. ОПРЕДЕЛЯЕМ ЯВЛЕНИЕ
#
# Явления размечены как:
#
# <div type="scene">
#
# Внутри такого <div> элемент <head> содержит название
# явления, например «Явление 1».
#
# Для каждой строки:
#
# 1. поднимаемся к предку <div type="scene">;
# 2. внутри него находим <head>;
# 3. извлекаем текст.
# ------------------------------------------------------------

scenes <- line_nodes |>
  xml_find_first(
    "ancestor::tei:div[@type='scene']/tei:head",
    ns = ns
  ) |>
  xml_text() |>
  trimws()

head(scenes)


# ------------------------------------------------------------
# 16. ОПРЕДЕЛЯЕМ ДЕЙСТВИЕ
#
# Действия размечены как:
#
# <div type="act">
#
# Логика запроса такая же, как для явлений.
# ------------------------------------------------------------

acts <- line_nodes |>
  xml_find_first(
    "ancestor::tei:div[@type='act']/tei:head",
    ns = ns
  ) |>
  xml_text() |>
  trimws()

head(acts)


# ------------------------------------------------------------
# 17. СОБИРАЕМ ТАБЛИЦУ
#
# Все четыре вектора имеют одинаковую длину:
#
# - act;
# - scene;
# - speaker;
# - text.
#
# Поэтому их можно объединить в tibble.
# ------------------------------------------------------------

woe_from_wit <- tibble(
  act = acts,
  scene = scenes,
  speaker = speakers,
  text = line_text
)

woe_from_wit


# ------------------------------------------------------------
# Проверяем первые строки таблицы.
# ------------------------------------------------------------

woe_from_wit |>
  slice_head(n = 10)


# ------------------------------------------------------------
# 18. НЕБОЛЬШОЙ АНАЛИЗ
#
# Посчитаем, сколько строк произносит каждый персонаж.
#
# count() группирует таблицу по speaker
# и создаёт столбец n с количеством строк.
# ------------------------------------------------------------

speaker_counts <- woe_from_wit |>
  count(
    speaker,
    sort = TRUE
  )

speaker_counts


# ------------------------------------------------------------
# Покажем десять персонажей
# с наибольшим количеством строк.
# ------------------------------------------------------------

speaker_counts |>
  slice_head(n = 10)


# ------------------------------------------------------------
# Визуализируем результат.
#
# reorder(speaker, n) располагает персонажей
# по количеству строк.
#
# coord_flip() разворачивает диаграмму,
# чтобы длинные имена легче читались.
# ------------------------------------------------------------

speaker_counts |>
  slice_head(n = 10) |>
  ggplot(
    aes(
      x = reorder(speaker, n),
      y = n
    )
  ) +
  geom_col() +
  coord_flip() +
  labs(
    title = "Персонажи с наибольшим количеством строк",
    x = "Персонаж",
    y = "Количество строк"
  )
