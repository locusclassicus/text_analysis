#
# Схематически структура выглядит так:
#
# casting
# ├── актер 1
# │   ├── поле 1
# │   ├── поле 2
# │   └── поле 3
# ├── актер 2
# │   ├── поле 1
# │   ├── поле 2
# │   └── поле 3
# └── ...
#
# Наша задача:
#
# 1. извлечь список casting;
# 2. преобразовать каждый его элемент в таблицу;
# 3. объединить получившиеся таблицы по строкам.
# ------------------------------------------------------------

tbbt |>
  pluck("casting") |>
  map_dfr(as_tibble)

# ----------------------------------------------------------
# map_dfr() применяет функцию к каждому элементу списка,
# а затем объединяет результаты в одну таблицу.
#
# В данном случае к каждому внутреннему списку
# применяется функция as_tibble().
#
# as_tibble() преобразует один элемент casting
# в небольшую таблицу.
#
# Буквы dfr можно понимать как:
#
# df — data frame, то есть таблица;
# r  — rows, то есть объединение по строкам.
#
# В результате каждый актер становится
# отдельной строкой общей таблицы.
# ----------------------------------------------------------

# КАК ЕЩЕ ЭТО МОЖНО СДЕЛАТЬ (ВАРИАНТ СТУДЕНТОВ)

