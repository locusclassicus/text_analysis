# ------------------------------------------------------------
# ЦИКЛ FOR
#
# Нам нужно применить одну и ту же функцию
# к каждому элементу списка pastries.
#
# В отличие от nchar(), функция get_name()
# написана для одного отдельного списка.
#
# Поэтому элементы нужно перебрать.
# ------------------------------------------------------------


# Результатом будут текстовые значения.
#
# Заранее создаем пустой вектор

pastry_names_for <- c()


# seq_along(pastries) создает номера элементов:
#
# 1, 2, 3, ... до длины списка.

for (i in seq_along(pastries)) {
  
  # pastries[[i]] — текущий внутренний список.
  #
  # get_name() извлекает из него название.
  #
  # Результат записываем на позицию i.
  
  pastry_names_for[i] <- get_name(pastries[[i]])
  
}

pastry_names_for

# ------------------------------------------------------------
# MAP_CHR()
#
# map_chr() применяет функцию к каждому элементу
# списка и собирает результаты в символьный вектор.
#
# Аргументы:
#
# 1. pastries — список, который обрабатываем;
# 2. get_name — функция для одного элемента.
# ------------------------------------------------------------

pastry_names_map <- map_chr(
  pastries,
  get_name
)

pastry_names_map

