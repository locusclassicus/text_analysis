# УСЛОВИЕ ВНУТРИ ФУНКЦИИ
#
# Функция получает один элемент списка и возвращает строку.
# Если страна указана, добавляет ее к названию.
# Если нет — сообщает об отсутствии информации.
# ------------------------------------------------------------

describe_pastry <- function(pastry) {
  
  if ("country" %in% names(pastry)) {
    paste(pastry$name, pastry$country, sep = ": ")
  } else {
    paste(pastry$name, "страна не указана", sep = ": ")
  }
  
}

