#
# В предыдущей шпаргалке мы просили модель
# извлечь людей из письма.
#
# Ответ получился в виде обычного текста.
# Такой ответ удобно читать человеку,
# но неудобно обрабатывать в R.
#
# Сегодня мы попросим модель вернуть ответ
# в специальном формате — JSON.
#
# JSON — это обычный текст,
# записанный по строгим правилам.
#
# Его используют программы,
# чтобы обмениваться данными.
#
# Затем мы превратим JSON
# в обычную таблицу R.
# ============================================================


chat <- chat_ollama(
  model = "gemma4:31b-cloud",
  credentials = function() Sys.getenv("OLLAMA_API_KEY"),
)

# ------------------------------------------------------------
# СОСТАВЛЯЕМ ПРОМПТ
# ------------------------------------------------------------
#
# Просим модель:
#
# 1. найти всех людей;
# 2. вернуть ответ в формате JSON.
#
# Для каждого человека нужны три поля:
#
# name
# description
# quote
# ------------------------------------------------------------

prompt_json <- "
Извлеки всех людей, прямо упомянутых в письме.

Для каждого человека укажи три поля:
- name — имя точно в той форме, в которой оно встречается в тексте;
- description — краткое описание человека;
- quote — дословную цитату из письма с этим именем.

Используй только информацию из текста письма.
Не дополняй имена на основании внешних знаний.

Верни результат в формате JSON.

Если в письме нет ни одного названного человека,
верни пустой список [].

Верни только JSON, без пояснений и без Markdown.
"

# Посмотрим на промпт.

cat(prompt_json)


# ------------------------------------------------------------
# ОТПРАВЛЯЕМ ЗАПРОС
# ------------------------------------------------------------

answer <- chat$chat(
  prompt_json,
  letter
)


# Посмотрим, что вернула модель.

cat(answer)


# ------------------------------------------------------------
# ЧТО ТАКОЕ JSON?
# ------------------------------------------------------------
#
# Ответ модели по-прежнему является текстом.
#
# Но теперь этот текст записан
# по строгим правилам.
#
# Например, один человек выглядит так:
#
# {
#   "name": "Олег",
#   "description": "русский князь",
#   "quote": "Войны Олега..."
# }
#
# Если людей несколько,
# они записываются друг за другом
# в квадратных скобках.
#
# JSON удобно читать программам.
# ------------------------------------------------------------

# ------------------------------------------------------------
# ЗАДАЕМ КАТЕГОРИИ ЗАРАНЕЕ
# ------------------------------------------------------------
#
# Свободное поле description модель заполняет непоследовательно.
# Поэтому вместо него зададим небольшой набор категорий.
#
# Это называется классификацией:
# модель не придумывает описание, а выбирает
# один вариант из предложенного списка.

prompt_json <- "
Извлеки всех людей, прямо упомянутых в письме.

Для каждого человека укажи три поля:

- name_raw — имя точно в той форме и на том языке, на котором оно встречается в тексте;
- name - начальная форма имени по-русски, если ее возможно уверенно восстановить;

- type — выбери ОДНО из следующих значений:
  historical — исторический деятель;
  religious — религиозный или библейский персонаж;
  contemporary — современник автора письма;
  literary — литературный или мифологический персонаж;
  unknown — если определить категорию невозможно;

- quote — дословную цитату из письма с этим именем.

Если категория не очевидна, используй unknown.
Не оставляй поле type пустым.

Верни результат в формате JSON.

Если в письме нет ни одного названного человека,
верни пустой список [].

Верни только JSON, без пояснений и Markdown.
"

answer <- chat$chat(
  prompt_json,
  letter
)

cat(answer)

# ------------------------------------------------------------
# ЧИТАЕМ JSON В R
# ------------------------------------------------------------
#
# Функция fromJSON()
# превращает JSON в объект R.
# ------------------------------------------------------------

library(jsonlite)

answer <- answer |>
  str_replace("^```json\\s*", "") |>
  str_replace("\\s*```$", "")

people <- fromJSON(answer)


# Посмотрим результат.

people


# ------------------------------------------------------------
# ЧТО ПОЛУЧИЛОСЬ?
# ------------------------------------------------------------
#
# Теперь это уже не текст.
# Это обычная таблица.
# ------------------------------------------------------------

class(people)
str(people)


# ------------------------------------------------------------
# РАБОТАЕМ С ТАБЛИЦЕЙ
# ------------------------------------------------------------

# Имена всех людей.

people$name


# Все описания.

people$description


# Все цитаты.

people$quote


# Сколько людей нашла модель?

nrow(people)


# ------------------------------------------------------------
# СОХРАНЯЕМ ТАБЛИЦУ
# ------------------------------------------------------------

write.csv(
  people,
  "pushkin_people.csv",
  row.names = FALSE,
  fileEncoding = "UTF-8"
)

