# Мы уже умеем:
#
# 1. читать несколько текстовых файлов;
# 2. отправлять каждый текст LLM;
# 3. получать JSON;
# 4. превращать JSON в таблицу;
# 5. повторять эту процедуру для множества файлов с помощью map().
#
# Но при обработке большого количества документов
# почти неизбежно что-нибудь пойдет не так.
#
# Например:
#
# - модель вернула невалидный JSON;
# - добавила ```json перед ответом;
# - вернула обычный текст вместо JSON;
# - соединение с моделью временно прервалось;
# - один из файлов оказался пустым или необычно устроенным.
#
# Если мы обрабатываем 200 писем, не хочется терять
# результаты 199 писем из-за одной ошибки.
#
# В этой шпаргалке научимся:
#
# - находить проблемный файл;
# - не останавливать обработку из-за одной ошибки;
# - собирать список файлов, которые надо проверить;
# - сохранять результаты на диск.


# ------------------------------------------------------------
# 1. ПОДКЛЮЧАЕМ ПАКЕТЫ
# ------------------------------------------------------------

library(purrr)
library(jsonlite)
library(dplyr)


# ------------------------------------------------------------
# 2. НАШИ ФАЙЛЫ
# ------------------------------------------------------------
#
# Предполагаем, что тексты лежат в папке letters.

letters <- list.files(
  "files/llm/letters",
  pattern = "\\.txt$",
  full.names = TRUE
)

letters


# ------------------------------------------------------------
# 3. ЧТО ОЗНАЧАЕТ ОШИБКА map()?
# ------------------------------------------------------------
#
# Представим, что мы запускаем уже знакомую команду:

results <- map(
  letters,
  extract_people
)

# Иногда вместо результата мы можем получить сообщение:
#
# Error in `map()`:
# ℹ In index: 2.
#
# Это не означает, что проблема обязательно в map().
#
# map() сообщает нам, что ошибка произошла
# при обработке ВТОРОГО элемента нашего вектора files.
#
# Посмотрим, какой это файл:

letters[2]


# ------------------------------------------------------------
# 4. НО МОЖНО ЛИ ВООБЩЕ НЕ ОСТАНАВЛИВАТЬСЯ?
# ------------------------------------------------------------
#
# Да.
#
# В пакете purrr есть функция possibly().
#
# Она позволяет сказать:
#
# "Попробуй выполнить функцию.
#  Если получится — сохрани результат.
#  Если произойдет ошибка — верни другое значение
#  и продолжай работу."
#
# Сделаем безопасную версию нашей функции extract_people().

safe_extract_people <- possibly(
  extract_people,
  otherwise = NULL
)


# ------------------------------------------------------------
# 5. ЗАПУСКАЕМ БЕЗОПАСНУЮ ОБРАБОТКУ
# ------------------------------------------------------------

results <- map(
  letters,
  safe_extract_people
)

results_tbl <- results |> 
  bind_rows()


# Теперь ошибка в одном письме
# не остановит обработку остальных.
#
# Для успешно обработанных файлов мы получим таблицы.
#
# Для файлов, на которых произошла ошибка, —
# специальное значение NULL.

# NULL означает отсутствие результата.

# Проверим, какие результаты равны NULL.

failed <- map_lgl(
  results,
  is.null
)

failed


