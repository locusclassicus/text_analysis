# 9. СРАВНИВАЕМ РЕЗУЛЬТАТЫ
# ------------------------------------------------------------
#
# Мы выполнили одну и ту же задачу несколько раз:
#
# 1. простой список людей;
# 2. список с уточненными правилами;
# 3. таблица с описаниями и цитатами;
# 4. таблица с запретом на внешние дополнения.
#
# С каждым шагом промпт становился длиннее,
# но одновременно становились явнее
# правила исследовательской работы.
#
# Промпт описывает:
#
# - объект извлечения;
# - критерии включения;
# - критерии исключения;
# - форму результата;
# - способ проверки результата.
#
# Поэтому хороший промпт — это не набор волшебных слов,
# а формализованный исследовательский протокол.
# ------------------------------------------------------------


