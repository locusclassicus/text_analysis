# ------------------------------------------------------------
#  НОВЫЙ ЧАТ ДЛЯ НОВОЙ ЗАДАЧИ
# ------------------------------------------------------------
#
# В предыдущей шпаргалке мы уже работали
# с  письмом в объекте chat.
#
# Однако для нового независимого эксперимента
# лучше создать новый чат.
#
# Так результат не будет зависеть
# от предыдущих сообщений и ответов модели.
#
# Используйте тот же способ подключения,
# который был показан в шпаргалке № 1.
# ------------------------------------------------------------

chat <- chat_ollama(
  model = "gemma4:31b-cloud",
  credentials = function() Sys.getenv("OLLAMA_API_KEY"),
)

# ------------------------------------------------------------
# 3. ПРОСТОЙ ЗАПРОС
# ------------------------------------------------------------
#
# Начнем с максимально простой инструкции:
# "Извлеки всех людей, упомянутых в письме".
# Инструкция и текст письма передаются
# в одном вызове chat$chat().
# ------------------------------------------------------------

people <- chat$chat(
  "Извлеки всех людей, упомянутых в этом письме.",
  letter
)


# Выводим ответ модели.

people


# ------------------------------------------------------------
# 4. ПРОВЕРКА РЕЗУЛЬТАТА
# ------------------------------------------------------------
#
# Модель, скорее всего, вернет обычный список имен.
#
# Такой ответ легко прочитать человеку,
# но его недостаточно для исследования.
#
# Нужно проверить:
#
# - все ли имена найдены;
# - не добавлены ли люди, которых нет в тексте;
# - включены ли исторические лица;
# - включен ли подразумеваемый адресат письма;
# - как обработаны фамилии со знаком вопроса;
# - не перепутаны ли люди, народы и организации.
#
# Уже на этом этапе становится видно:
# команда "извлеки всех людей" недостаточно точна.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 5. УТОЧНЯЕМ ИССЛЕДОВАТЕЛЬСКУЮ ЗАДАЧУ
# ------------------------------------------------------------
#
# Укажем, кого именно следует включать в результат.
#
# Включаем:
#
# - людей, названных по имени или фамилии;
# - исторических и религиозных деятелей;
# - людей, названных только по имени;
# - людей, рядом с которыми стоит знак вопроса в скобках.
#
# Не включаем:
#
# - народы;
# - государства;
# - города;
# - организации;
# - автора и адресата, если они не названы в самом тексте.
#
# Последнее условие особенно важно.
#
# Модель может знать, кто написал письмо и кому оно адресовано,
# но в этом упражнении она должна опираться
# только на переданный текст.
# ------------------------------------------------------------

prompt <- "
Извлеки всех людей, прямо упомянутых в письме.

Включай:
- людей, названных по имени или фамилии;
- исторических и религиозных деятелей.

Не включай:
- автора и адресата, если они не названы в тексте;
- народы;
- государства;
- города;
- организации.

Верни результат в виде списка.
"


people_detailed <- chat$chat(
  prompt,
  letter
)


people_detailed


# ------------------------------------------------------------
# 6. ДОБАВЛЯЕМ КОНТЕКСТ
# ------------------------------------------------------------
#
# Один список имен трудно проверить.
#
# Поэтому попросим модель указать для каждого человека:
#
# 1. имя в той форме, в которой оно встречается в тексте;
# 2. краткое описание;
# 3. точную цитату из письма.
#
# Цитата позволяет вернуться к источнику
# и проверить каждое извлеченное имя.
#
# Это важный принцип работы с LLM:
# результат + свидетельство из источника.
# ------------------------------------------------------------

prompt_evidence <- "
Извлеки всех людей, прямо упомянутых в письме.

Для каждого человека укажи:
1. имя в той форме, в которой оно встречается в тексте;
2. краткое описание;
3. дословную цитату из письма с этим именем.

Не включай автора и адресата, если они не названы непосредственно в тексте.

Не включай народы, государства, города и организации.

Верни результат в виде таблицы.
"



people_with_evidence <- chat$chat(
  prompt_evidence,
  letter
)


people_with_evidence

# ------------------------------------------------------------
# Знаки | разделяют таблицу на столбцы.
# Первая строка содержит названия столбцов.
# Каждая следующая строка — отдельное наблюдение.
#
# Такая запись называется таблицей Markdown.
# Markdown — это простой способ размечать текст.
#
# Важно: для нас это пока НЕ таблица R.
# Это обычный текст, который только выглядит как таблица.


# ------------------------------------------------------------
# 7. ПОЧЕМУ ЦИТАТА ВАЖНА
# ------------------------------------------------------------
#
# Языковая модель может:
#
# - пропустить имя;
# - неправильно определить человека;
# - добавить полное имя, которого нет в тексте;
# - заменить форму имени на современную;
# - использовать внешние знания вместо самого документа.
#
# Поэтому каждую строку результата желательно связывать
# с конкретным фрагментом источника.
#
# Например, в письме встречается:
# "А Александр, который привел вас в Париж?"
# Модель может решить, что речь идет
# об Александре I.
#
# Это исторически обоснованное предположение,
# но полного имени "Александр I" в тексте нет.
#
# Следовательно, нужно различать:
#
# - то, что прямо написано в источнике;
# - интерпретацию модели;
# - внешнее историческое знание.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 8. ЗАПРЕЩАЕМ МОДЕЛИ ДОПОЛНЯТЬ ИМЕНА
# ------------------------------------------------------------
#
# Для филологического или исторического исследования
# бывает важно сохранить именно форму источника.
#
# Поэтому добавим правило:
#
# не раскрывать сокращенные и неполные имена
# на основании внешних знаний.
# ------------------------------------------------------------

prompt_source <- "
Извлеки всех людей, прямо упомянутых в письме.

Для каждого человека укажи:

- name: имя точно в той форме, в которой оно встречается в источнике;
- description: краткое описание;
- quote: дословную цитату с упоминанием этого человека.

Используй только информацию из текста письма.

Не дополняй и не исправляй имена на основании внешних знаний.

Например, если в тексте написано «Александр», не заменяй это имя на «Александр I».

Если рядом с именем или фамилией стоит знак вопроса, сохрани его рядом с именем.

Не включай людей, которые только подразумеваются, но не названы непосредственно в тексте.

Не включай народы, государства, города и организации.

Верни результат в виде таблицы.
"



# Отправляем новую инструкцию и то же самое письмо.

people_source_only <- chat$chat(
  prompt_source,
  letter
)

people_source_only


