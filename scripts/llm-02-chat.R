# 1. прочитаем письмо из текстового файла;
# 2. проверим, что текст загрузился правильно;
# 3. передадим письмо языковой модели;
# 4. попросим модель кратко пересказать его содержание;
# 5. сохраним ответ модели в отдельную переменную.

# Пока мы работаем только с одним документом.
# Источник текста: http://az.lib.ru/p/pushkin_a_s/text_1836_perepiska_s_chaadaevym.shtml
# ============================================================


library(ellmer) # если не загружены ранее 
library(stringr) # для работы со строками, входит в tidyverse


# ------------------------------------------------------------
# 1. ЧТЕНИЕ ТЕКСТА ИЗ ФАЙЛА
# ------------------------------------------------------------
#
# Письмо хранится в обычном текстовом файле:
#
# llm/pushkin.txt
#
# Функция readLines() читает файл построчно.
#
# В результате получается символьный вектор:
# каждый элемент вектора соответствует одной строке файла.
# ------------------------------------------------------------

letter <- readLines("files/llm/pushkin.txt") |> # files/llm/ — папка с письмами
  str_c(collapse = " ")                # если у вас другой путь, просто удалите эту часть


# Предупреждение можно игнорировать. Проверяем результат.
# В консоли появятся строки прочитанного письма.

letter

# ------------------------------------------------------------
# 3. ПЕРВЫЙ ЗАПРОС К МОДЕЛИ
# ------------------------------------------------------------
#
# Объект chat был создан в предыдущей шпаргалке.
#
# Он хранит:
#
# - выбранную языковую модель;
# - настройки подключения;
# - историю разговора с моделью.
#
# Метод $chat() отправляет модели новое сообщение.
# ------------------------------------------------------------


# Сначала формулируем инструкцию отдельно от текста.
#
# Это делает код более понятным:
# мы сразу видим, какую именно задачу выполняет модель.
# Подробный промпт можно хранить в отдельном документе
# и читать при помощи readLines(), как мы делали выше

instruction <- "Перескажи содержание этого письма в одном предложении."


# ------------------------------------------------------------
# 4. ДОБАВЛЕНИЕ ДОКУМЕНТА К ИНСТРУКЦИИ
# ------------------------------------------------------------
#
# Модель должна получить:
#
# 1. инструкцию;
# 2. сам текст письма.
#
# Их можно объединить в один запрос.
#
# Мы явно обозначаем границу между инструкцией
# и анализируемым документом.
#
# Это особенно важно при работе с длинными текстами:
# модель должна понимать, где заканчивается задание
# и начинается источник.
# ------------------------------------------------------------

prompt <- paste(
  instruction,
  "",
  "ТЕКСТ ПИСЬМА:",
  letter,
  sep = "\n"
)


# Проверяем итоговый запрос перед отправкой.
#
# Это полезная исследовательская привычка:
# всегда нужно понимать, что именно получает модель.

cat(prompt)


# ------------------------------------------------------------
# 5. ОТПРАВКА ЗАПРОСА
# ------------------------------------------------------------
#
# Передаем подготовленный запрос объекту chat.
#
# Ответ модели сохраняем в переменную summary.
#
# Если не выполнить присваивание, ответ появится в консоли,
# но его будет неудобно использовать в дальнейшей работе.
# ------------------------------------------------------------

chat <- chat_ollama(
  model = "gemma4:31b-cloud",
  credentials = function() Sys.getenv("OLLAMA_API_KEY")
)

summary <- chat$chat(prompt)

# Выводим ответ модели.

summary


# ------------------------------------------------------------
# 6. ЧТО ИМЕННО СДЕЛАЛА МОДЕЛЬ
# ------------------------------------------------------------
#
# Модель получила не только вопрос, но и новый документ.
# Она выполнила задачу саммаризации.
# При этом ответ модели не является готовым исследовательским результатом.
# Это интерпретация текста, созданная моделью.
#
# Поэтому результат нужно проверять:
#
# - отражена ли основная тема письма;
# - не пропущена ли важная мысль;
# - не добавлена ли информация, которой нет в тексте;
# - действительно ли ответ состоит из одного предложения.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 7. ПОВТОРНЫЙ ЗАПРОС В ТОМ ЖЕ ЧАТЕ
# ------------------------------------------------------------
#
# Объект chat хранит историю разговора.
# Поэтому после первого запроса модель уже "помнит"
# переданное ей письмо.
# В следующем сообщении можно не передавать текст повторно.
# Можно попросить уточнить или изменить предыдущий ответ.
# ------------------------------------------------------------

shorter_summary <- chat$chat(
  "Теперь сократи пересказ до 20 слов."
)


shorter_summary

# считаем число пробелов для проверки
str_count(shorter_summary, " ")


# ------------------------------------------------------------
# ВАЖНО: ИСТОРИЯ ЧАТА
# ------------------------------------------------------------
#
# Повторный запрос работает, потому что объект chat
# хранит предыдущие сообщения.
# Это удобно, когда мы последовательно уточняем
# анализ одного документа.
#
# Но при переходе к новому письму нужно создать новый chat.
# Иначе модель может учитывать содержание предыдущего письма
# и смешивать несколько источников.
#
# Общее правило:
#
# один документ --один отдельный чат
# ------------------------------------------------------------


