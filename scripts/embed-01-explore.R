library(tidyverse)

# 1. ЧТО ТАКОЕ ВЕКТОР? ----------------------------------------
# Числовой вектор — упорядоченный набор чисел.
# Чтобы сравнивать два текста, нужно одинаковое значение
# координат: например, первая координата у обоих считает she,
# вторая — married, и так далее.
#
# Эмбеддинг тоже является вектором.
# Словом «эмбеддинг» в NLP обычно называют выученное
# плотное представление: его координаты получены из данных.
# Здесь различаем прозрачные частотные признаки и такие
# выученные признаки. Это различие способов представления,
# а не двух несовместимых типов математических объектов.

# 2. ЧЕТЫРЕ ТЕКСТА ДЛЯ СРАВНЕНИЯ ------------------------------
# A — брак ради обеспеченности.
# B — похожая ситуация, описанная другими словами.
# C — финансовая безопасность банка: общая лексика, другая тема.
# D — отказ от брака: близкая тема, другое решение.
texts <- tribble(
  ~id, ~text,
  "A", "She married him for financial security.",
  "B", "She wanted a husband who could provide a stable income.",
  "C", "The bank upgraded its financial security system.",
  "D", "She refused to marry him for financial security."
)

texts

# 3. ВЕКТОР ИЗ ЧАСТОТ СЛОВ ------------------------------------
# Разбиваем текст на слова, приводим к нижнему регистру
# и считаем вхождения каждого слова в каждом тексте.
# unnest_longer() делает отдельную строку для каждого слова.
counts <- texts |>
  mutate(word = str_extract_all(str_to_lower(text), "[a-z]+")) |>
  unnest_longer(word) |>
  count(id, word, name = "n")

# complete() добавляет отсутствующие сочетания «текст — слово».
# Если слова в тексте нет, его частота равна нулю.
# arrange() задаёт одинаковый порядок координат для всех текстов.
counts <- counts |>
  complete(id, word, fill = list(n = 0)) |>
  arrange(id, word)

# Каждый столбец — одно слово, каждая строка — вектор текста.
counts |>
  pivot_wider(names_from = word, values_from = n)

# Такое представление называют «мешком слов».
# Оно сохраняет частоты, но не порядок слов.
# Число координат равно числу разных слов в нашем словаре.
# В большом словаре много нулей: векторы называют разреженными.
#
# Подумайте: увидит ли этот способ сходство A и B?
# Почему A и C всё-таки имеют общие координаты?

# 4. TF-IDF: МЕНЯЕМ ВЕС СЛОВ ----------------------------------
# Частота — не единственный возможный вес.
# TF показывает долю слова в данном тексте.
# IDF повышает вес слов, встречающихся в меньшем числе текстов.
# Здесь используем IDF = log(число текстов / число текстов со словом).
#
# Например, she встречается в трёх текстах, bank — в одном.
# IDF слова bank будет выше. Это редкость в этих четырёх текстах,
# а не универсальная важность слова.
weights <- counts |>
  group_by(word) |>
  mutate(
    documents_with_word = sum(n > 0),
    idf = log(n_distinct(id) / documents_with_word)
  ) |>
  ungroup() |>
  group_by(id) |>
  mutate(
    tf = n / sum(n),
    tf_idf = tf * idf
  ) |>
  ungroup()

weights |>
  filter(n > 0) |>
  select(id, word, n, tf, idf, tf_idf)

# Словарь остался прежним: координаты всё ещё соответствуют словам.
# TF-IDF сам по себе не учится понимать синонимы и порядок слов.
# На четырёх фразах мы изучаем расчёт, а не оцениваем качество метода.

