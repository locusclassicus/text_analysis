letters <- list.files(
  "files/llm/letters",      # у вас может быть другой путь к файлам
  full.names = TRUE
)

# Посмотрим,
# сколько писем находится в папке.

length(letters)


# ------------------------------------------------------------
# ФУНКЦИЯ ДЛЯ АНАЛИЗА ОДНОГО ПИСЬМА
# ------------------------------------------------------------
#
# Чтобы не писать один и тот же код
# много раз,
# оформим его в виде функции.
#
# На вход функция получает
# имя файла.
#
# На выходе возвращает таблицу
# с найденными людьми.
# ------------------------------------------------------------

extract_people <- function(file) {
  
  # читаем письмо
  letter <- readLines(
    file,
    encoding = "UTF-8",
    warn = FALSE
  )
  
  # создаем новый чат
  chat <- chat_ollama(
    model = "gemma4:31b-cloud",
    credentials = function() Sys.getenv("OLLAMA_API_KEY"),
  )
  
  # отправляем письмо модели
  
  answer <- chat$chat(
    prompt_json,
    letter,
    echo = FALSE
  )
  
  # Иногда модель оборачивает JSON в Markdown:
  #
  # ```json
  # [...]
  # ```
  #
  # Удаляем эти служебные строки. 
  # Разкомментируйте код ниже, если возникла такая ошибка.
  
  answer <- answer |>
  str_replace("^```json\\s*", "") |>
  str_replace("\\s*```$", "")
  # 
  # превращаем JSON
  # в таблицу
  
  people <- fromJSON(answer)
  
  # добавляем имя файла,
  # чтобы потом понимать,
  # из какого письма получены данные
  
  people$file <- basename(file)
  
  people
  
}


# ------------------------------------------------------------
# ПРОБУЕМ НА ОДНОМ ПИСЬМЕ
# ------------------------------------------------------------

people <- extract_people(
  letters[2]
)

people


# ------------------------------------------------------------
# ОБРАБАТЫВАЕМ ВСЕ ПИСЬМА
# ------------------------------------------------------------
#
# map() означает:
#
# "выполни одну и ту же функцию для каждого элемента списка".
#
# В нашем случае — для каждого письма.
# ------------------------------------------------------------

results <- map(
  letters,
  extract_people
)

# Сколько таблиц получилось?

length(results)


# ------------------------------------------------------------
# СОБИРАЕМ ВСЕ ТАБЛИЦЫ В ОДНУ
# ------------------------------------------------------------

people <- bind_rows(results)

people


# ------------------------------------------------------------
# СКОЛЬКО ЛЮДЕЙ НАШЛА МОДЕЛЬ?
# ------------------------------------------------------------

nrow(people)


# ------------------------------------------------------------
# КТО ВСТРЕЧАЕТСЯ ЧАЩЕ ВСЕГО?
