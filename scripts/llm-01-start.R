# Кастомная функция 
generate_metaphor <- function(temp) {
  chat <- chat_ollama(
    model = "gpt-oss:20b-cloud",
    credentials = function() Sys.getenv("OLLAMA_API_KEY"),
    params = params(temperature = temp)
  )
  
  chat$chat("Придумай метафору для Digital Humanities (одно предложение)")
}

# Применяем функцию к разным значениям температуры
temperatures <- c(0, 0.5, 1, 1.5, 2)

results <- temperatures |>
  map_chr(generate_metaphor)

# Собираем результаты в таблицу
tibble(
  temperature = temperatures,
  metaphor = results
)

