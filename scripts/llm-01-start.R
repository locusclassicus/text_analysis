# ------------------------------------------------------------
# ЧТО ДЕЛАЕТ chat()?
#
# Метод chat()
#
# отправляет сообщение модели;
# получает ответ;
# автоматически добавляет вопрос и ответ в историю диалога.
#
# Поэтому второй вопрос
# будет учитывать первый.
#
# Именно поэтому многие модели
# способны поддерживать длинный разговор.
# ------------------------------------------------------------



# ------------------------------------------------------------
# ПОЧЕМУ ЭТО ВАЖНО?
#
# В исследовательской работе
# нам часто НЕ нужна память модели.
#
# Например,
# если мы анализируем 500 документов,
# каждый документ должен обрабатываться
# независимо.
#
# Поэтому для каждого документа
# обычно создают новый чат.
#
# Иначе предыдущие документы
# могут повлиять на следующий ответ.
# ------------------------------------------------------------

