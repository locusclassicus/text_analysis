url <- "https://www.corpusthomisticum.org/sth2001.html"

summa_html <- read_html(url)

summa_html

# ============================================================
# СТРУКТУРА SUMMA THEOLOGIAE
# ============================================================


# ------------------------------------------------------------
# 10. СМОТРИМ НА СТРУКТУРУ СТРАНИЦЫ
#
# На странице Corpus Thomisticum текст Summa Theologiae
# уже размечен при помощи HTML.
#
# Например:
#
# <DIV CLASS="D">Quaestio 1</DIV>
#
# <DIV CLASS="E">Articulus 1</DIV>
#
# <P TITLE="I-II q. 1 a. 1 arg. 1">
#   ...
# </P>
#
# <P TITLE="I-II q. 1 a. 1 co.">
#   ...
# </P>
#
# Каждый содержательный фрагмент уже находится
# в отдельном элементе <p>.
# ------------------------------------------------------------


# ------------------------------------------------------------
# Сначала посмотрим на заголовки вопросов.
#
# На сайте они размечены так:
#
# <div class="D">Quaestio 1</div>
#
# CSS-селектор
#
# div.D
#
# означает:
# выбрать элементы <div>, у которых class="D".
# ------------------------------------------------------------

summa_html |>
  html_elements("div.D") |>
  html_text2() 


# ------------------------------------------------------------
# Аналогично заголовки артикулов размечены:
#
# <div class="E">Articulus 1</div>
# ------------------------------------------------------------

summa_html |>
  html_elements("div.E") |>
  html_text2() 


# ------------------------------------------------------------
# Но для построения таблицы эти заголовки нам даже
# не понадобятся.
#
# Главная информация находится в элементах <p>.
#
# Посмотрим на первые элементы <p> страницы.
# ------------------------------------------------------------

summa_html |>
  html_elements("p") 

# ------------------------------------------------------------
# Не все <p> на странице обязательно относятся
# к основному тексту Summa.
#
# Поэтому воспользуемся атрибутом title.
#
# У содержательных фрагментов он выглядит, например, так:
#
# <p title="I-II q. 1 pr.">
#
# <p title="I-II q. 1 a. 1 arg. 1">
#
# <p title="I-II q. 1 a. 1 s. c.">
#
# <p title="I-II q. 1 a. 1 co.">
#
# <p title="I-II q. 1 a. 1 ad 1">
#
# CSS-селектор
#
# p[title]
#
# означает:
# выбрать все элементы <p>, у которых есть
# атрибут title.
#
# Квадратные скобки в CSS-селекторе позволяют
# задавать условие по атрибуту.
# ------------------------------------------------------------

paragraphs <- summa_html |>
  html_elements("p[title]")

paragraphs

# ------------------------------------------------------------
# Проверим, сколько таких фрагментов находится
# на странице q. 1–5.
# ------------------------------------------------------------

length(paragraphs)


# ============================================================
# ИЗВЛЕКАЕМ МЕТАДАННЫЕ
# ============================================================


# ------------------------------------------------------------
# 11. АТРИБУТ TITLE
#
# Атрибут title уже содержит структурную информацию
# о каждом фрагменте.
#
# Например:
#
# I-II q. 1 pr.
#
# I-II q. 1 a. 1 arg. 1
#
# I-II q. 1 a. 1 s. c.
#
# I-II q. 1 a. 1 co.
#
# I-II q. 1 a. 1 ad 1
#
# Здесь:
#
# q. 1    — quaestio 1;
# a. 1    — articulus 1;
# pr.     — prooemium;
# arg. 1  — первый аргумент;
# s. c.   — sed contra;
# co.     — corpus articuli, то есть respondeo;
# ad 1    — ответ на первый аргумент.
#
# html_attr("title") извлекает значение этого атрибута.
# ------------------------------------------------------------

labels <- paragraphs |>
  html_attr("title")

head(labels, 10)


# ------------------------------------------------------------
# Обратите внимание:
#
# здесь HTML уже сделал за нас существенную часть работы.
#
# Нам не нужно искать в тексте, где начинается новый
# аргумент или respondeo.
#
# Один элемент <p> = один содержательный фрагмент.
#
# А его положение в структуре Summa записано
# в атрибуте title.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 12. СТАБИЛЬНЫЙ ИДЕНТИФИКАТОР
#
# В начале каждого фрагмента находится ссылка:
#
# <a name="33406">
#
# Число 33406 — стабильный идентификатор
# данного фрагмента в Corpus Thomisticum.
#
# Внутри каждого <p> сначала находим элемент <a>,
# а затем извлекаем его атрибут name.
#
# html_element() здесь используется в единственном числе,
# потому что для каждого абзаца нам нужен один элемент <a>.
# ------------------------------------------------------------

ids <- paragraphs |>
  html_element("a") |>
  html_attr("name")

head(ids)


# ------------------------------------------------------------
# Сравним идентификаторы и структурные метки.
#
# Поскольку оба вектора получены из одного набора paragraphs,
# элементы сохраняют соответствие:
#
# первый id относится к первому label,
# второй id — ко второму label и т. д.
# ------------------------------------------------------------

tibble(
  id = ids,
  label = labels
) |>
  slice_head(n = 10)


# ============================================================
# ИЗВЛЕКАЕМ ТЕКСТ
# ============================================================


# ------------------------------------------------------------
# 13. ТЕКСТ ФРАГМЕНТОВ
#
# html_text2() извлекает видимый текст каждого <p>.
#
# Поскольку paragraphs содержит много элементов,
# результатом будет вектор:
#
# один элемент вектора = один фрагмент Summa.
# ------------------------------------------------------------

texts <- paragraphs |>
  html_text2()

head(texts)


# ------------------------------------------------------------
# Однако в начале каждого <p> находится служебная ссылка
# Corpus Thomisticum.
#
# Например HTML выглядит примерно так:
#
# <p title="I-II q. 1 a. 1 arg. 1">
#
#   <a name="33406">
#     <span class="ref">
#       [33406] Iª-IIae q. 1 a. 1 arg. 1
#     </span>
#   </a>
#
#   Ad primum sic proceditur...
#
# </p>
#
# Поэтому html_text2() возвращает не только текст Фомы,
# но и напечатанную в начале ссылку:
#
# [33406] Iª-IIae q. 1 a. 1 arg. 1
# Ad primum sic proceditur...
#
# Эту ссылку нужно удалить.
# ------------------------------------------------------------


# ------------------------------------------------------------
# Сначала извлечём её отдельно.
#
# Она находится внутри элемента:
#
# <span class="ref">
#
# CSS-селектор .ref означает:
# выбрать элемент с class="ref".
# ------------------------------------------------------------

refs <- paragraphs |>
  html_element(".ref") |>
  html_text2()

head(refs)


# ------------------------------------------------------------
# Теперь у нас есть два параллельных вектора:
#
# texts — полный текст каждого <p>;
# refs  — служебная ссылка в начале этого же <p>.
#
# str_remove() удаляет refs из соответствующих texts.
#
# fixed() означает, что строку нужно воспринимать буквально,
# а не как регулярное выражение.
#
# str_squish() убирает лишние пробелы.
# ------------------------------------------------------------

texts_clean <- str_remove(
  texts,
  fixed(refs)
) |>
  str_squish()

head(texts_clean)


# ------------------------------------------------------------
# Проверим на первом аргументе.
# ------------------------------------------------------------

labels[2]

texts_clean[2]


# ============================================================
# СОБИРАЕМ ПЕРВУЮ ТАБЛИЦУ
# ============================================================


# ------------------------------------------------------------
# 14. ОБЪЕДИНЯЕМ ДАННЫЕ
#
# Теперь для каждого фрагмента у нас есть:
#
# id    — стабильный идентификатор Corpus Thomisticum;
# label — структурная метка;
# text  — собственно текст Фомы.
#
# Все три вектора имеют одинаковую длину,
# поэтому их можно объединить в tibble.
# ------------------------------------------------------------

summa_raw <- tibble(
  stable_id = ids,
  label = labels,
  text = texts_clean
)

summa_raw

# save(summa_raw, file = "ST.Rdata")
# load("data/ST.Rdata")

# ------------------------------------------------------------
# Посмотрим первые строки.
# ------------------------------------------------------------

summa_raw |>
  slice_head(n = 10)


# ============================================================
# РАЗБИРАЕМ СТРУКТУРНУЮ МЕТКУ
# ============================================================


# ------------------------------------------------------------
# 15. НОМЕР ВОПРОСА
#
# Теперь пригодятся регулярные выражения из прошлого урока.
#
# Но regex работает уже не с огромным текстом страницы,
# а с коротким и регулярным столбцом label.
#
# Например:
#
# I-II q. 1 a. 1 arg. 1
#
# Нам нужно извлечь число после q.
#
# В шаблоне:
#
# q\\.       — буквальный текст q.
# \\s+       — один или несколько пробелов;
# (\\d+)     — одна или несколько цифр.
#
# Круглые скобки создают группу захвата.
# ------------------------------------------------------------

summa_raw <- summa_raw |>
  mutate(
    question = str_match(
      label,
      "q\\.\\s+(\\d+)"
    )[, 2]
  ) 

# ------------------------------------------------------------
# 16. НОМЕР АРТИКУЛА
#
# Аналогично извлекаем число после a.
#
# У prooemium номера артикула нет,
# поэтому для него получим NA.
# ------------------------------------------------------------

summa_raw <- summa_raw |>
  mutate(
    article = str_match(
      label,
      "a\\.\\s+(\\d+)"
    )[, 2]
  ) 


# ------------------------------------------------------------
# 17. ТИП ФРАГМЕНТА
#
# Теперь определяем тип по окончанию структурной метки.
#
# Возможны:
#
# pr.      — prooemium;
# arg. N   — argumentum;
# s. c.    — sed contra;
# co.      — respondeo;
# ad N     — responsio.
# ------------------------------------------------------------

summa_type <- summa_raw |>
  mutate(
    type = case_when(
      str_detect(label, "q\\.\\s+\\d+\\s+pr\\.$") ~
        "prooemium",
      
      str_detect(label, "a\\.\\s+\\d+\\s+arg\\.\\s+\\d+$") ~
        "argumentum",
      
      str_detect(label, "s\\.\\s*c\\.$") ~
        "sed contra",
      
      str_detect(label, "a\\.\\s+\\d+\\s+co\\.$") ~
        "respondeo",
      
      str_detect(label, "a\\.\\s+\\d+\\s+ad\\s+\\d+$") ~
        "responsio"
    )
  ) 


# ------------------------------------------------------------
# 18. НОМЕР АРГУМЕНТА ИЛИ ОТВЕТА
#
# Для argumentum и responsio полезно отдельно сохранить
# их порядковый номер.
#
# Например:
#
# arg. 3  -> 3
#
# ad 2    -> 2
#
# У prooemium, sed contra и respondeo такого номера нет.
# ------------------------------------------------------------


# ------------------------------------------------------------
# Теперь собираем всё в одну готовую таблицу.
#
# stable_id, question и article преобразуем в integer,
# чтобы номера хранились как числа, а не как строки.

# str_match() всегда возвращает не одно значение, а матрицу совпадений.
# q. 1   <- полное совпадение
# 1      <- то, что попало в круглые скобки (\d+)
# ------------------------------------------------------------

summa_1_5 <- summa_raw |>
  mutate(
    
    stable_id = as.integer(stable_id),
    
    question = as.integer(
      str_match(
        label,
