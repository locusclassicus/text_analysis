# ------------------------------------------------------------
# 9. ЧТЕНИЕ ВЕБ-СТРАНИЦЫ
#
# read_html() умеет читать не только локальный HTML-файл,
# но и страницу непосредственно по URL.
#
# Для начала возьмём первую страницу Prima Secundae,
# которая содержит вопросы 1-5.
