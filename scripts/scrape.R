library(tidyverse)
library(rvest)
# library(polite)

# ============================================================
# ВЕБ-СКРЕЙПИНГ В R: ШПАРГАЛКА К УРОКУ
#
# Веб-скрейпинг — автоматическое извлечение данных
# с веб-страниц.
#
# Большинство веб-страниц написано на HTML.
# HTML, как и XML, имеет древовидную структуру:
#
# - элементы обозначаются тегами;
# - элементы могут быть вложены друг в друга;
# - элементы могут содержать текст;
# - у элементов могут быть атрибуты;
# - нужные элементы можно находить при помощи CSS-селекторов.
#
# Пакет rvest позволяет:
#
# - скачать и прочитать HTML;
# - находить элементы страницы;
# - извлекать из них текст;
# - извлекать атрибуты, например ссылки;
# - превращать содержимое сайта в таблицу.
#
# В качестве основного примера используем Corpus Thomisticum:
# https://www.corpusthomisticum.org/
#
# Наша итоговая задача — собрать в таблицу
# Prima Secundae из Summa Theologiae Фомы Аквинского.
# ============================================================


# ------------------------------------------------------------
# 1. СОЗДАЁМ ПРОСТОЙ HTML-ДОКУМЕНТ
#
# Сначала потренируемся на маленьком искусственном HTML.
#
# minimal_html() создаёт минимальный HTML-документ из строки.
# Это удобно, потому что мы точно знаем его структуру.
#
# В примере ниже:
#
# <h1> — заголовок;
# <div> — блок страницы;
# <p> — абзац;
# <a> — ссылка.
#
# Атрибут class задаёт класс элемента.
# Атрибут id задаёт уникальный идентификатор.
# Атрибут href содержит адрес ссылки.
# ------------------------------------------------------------

example_html <- minimal_html("
<html>
  <body>
    <h1 id='title'>Summa Theologiae</h1>

    <div class='question'>
      <h2>Quaestio 1</h2>

      <p class='argument'>
        Videtur quod homini non conveniat agere propter finem.
      </p>

      <p class='answer'>
        Respondeo dicendum quod omnes actiones humanae propter finem sunt.
      </p>

      <a class='next' href='sth2006.html'>Quaestiones 6-21</a>
    </div>
  </body>
</html>
")

example_html


# ------------------------------------------------------------
# 2. HTML КАК ДЕРЕВО
#
# HTML-документ состоит из вложенных элементов.
#
# В нашем примере:
#
# <html>
#   <body>
#     <h1>...</h1>
#     <div>
#       <h2>...</h2>
#       <p>...</p>
#       <p>...</p>
#       <a>...</a>
#     </div>
#   </body>
# </html>
#
# Нас обычно интересует не весь документ целиком,
# а отдельные элементы внутри него.
# ------------------------------------------------------------


# ------------------------------------------------------------
# 3. CSS-СЕЛЕКТОРЫ
#
# Чтобы извлечь данные из HTML, нужно указать,
# какие именно элементы страницы нас интересуют.
#
# Для этого используются CSS-селекторы.
#
# CSS-селекторы — это шаблоны форматирования стилей для элементов веб-страниц.
#
# Самые простые варианты:
#
# p
#   выбрать все элементы <p>
#
#
# .argument
#   выбрать все элементы с class="argument"
#
# #title
#   выбрать элемент с id="title"
#
# .question p
#   выбрать все <p>, находящиеся внутри элемента
#   с class="question"
#
# Обратите внимание:
#
# точка . означает class;
# решётка # означает id;
# имя без специальных знаков означает HTML-тег.
# ------------------------------------------------------------


# ------------------------------------------------------------
# html_elements() находит ВСЕ элементы,
# соответствующие CSS-селектору.
#
# ------------------------------------------------------------

paragraph_nodes <- example_html |>
  html_elements("p")

paragraph_nodes

# Все ссылки:

example_html |>
  html_elements("a")


# Все элементы с class="argument":

example_html |>
  html_elements(".argument")


# ------------------------------------------------------------
# Заголовок <h1> на странице один.
#
# html_element() возвращает ПЕРВЫЙ подходящий элемент.
# html_elements() возвращает ВСЕ подходящие элементы.
# ------------------------------------------------------------

example_html |>
  html_element("h1") 

# ------------------------------------------------------------
# 4. ИЗВЛЕЧЕНИЕ ТЕКСТА
#
# html_text2() извлекает видимый текст элемента.
#
# В отличие от самого HTML-узла, результат уже является
# обычной строкой, с которой можно работать при помощи stringr.
# ------------------------------------------------------------

paragraph_nodes |>
  html_text2()


# ------------------------------------------------------------
# Можно сразу объединить поиск элемента и извлечение текста.
# ------------------------------------------------------------

example_html |>
  html_element("h1") |>
  html_text2()


# ------------------------------------------------------------
# 5. CSS-СЕЛЕКТОРЫ: КЛАСС
#
# Часто одного имени тега недостаточно.
# Например, на странице может быть много разных <p>.
#
# CSS позволяет выбирать элементы по классу.
#
# .argument означает:
# найти элемент с class="argument".
#
# Точка перед именем — обозначение класса в CSS.
# ------------------------------------------------------------

example_html |>
  html_element(".argument") |>
  html_text2()


# ------------------------------------------------------------
# Аналогично выбираем ответ.
# ------------------------------------------------------------

example_html |>
  html_element(".answer") |>
  html_text2()


# ------------------------------------------------------------
# Можно одновременно указать тег и класс.
#
# p.argument означает:
# элемент <p> с class="argument".
# ------------------------------------------------------------

example_html |>
  html_element("p.argument") |>
  html_text2()

# ------------------------------------------------------------
# 6. CSS-СЕЛЕКТОРЫ: ID
#
# #title означает:
# найти элемент с id="title".
#
# Решётка перед именем — обозначение id в CSS.
#
# В отличие от class, id обычно должен быть уникальным
# внутри одной страницы.
# ------------------------------------------------------------

example_html |>
  html_element("#title") |>
  html_text2()


# ------------------------------------------------------------
# 7. ВЛОЖЕННЫЕ ЭЛЕМЕНТЫ
#
# CSS-селектор может описывать не только один элемент,
# но и его положение в дереве.
#
# .question p означает:
# найти все <p>, которые находятся внутри элемента
# с class="question".
# ------------------------------------------------------------

example_html |>
  html_elements(".question p") |>
  html_text2()

# ------------------------------------------------------------
# Важно:
#
# ".question p"
#   пробел означает вложенность:
#   выбрать <p> внутри элемента class="question"
#
# "p.question"
#   пробела нет:
#   выбрать <p>, у которого самого class="question"

example_html |>
  html_elements("p.question") |>
  html_text2()

# ------------------------------------------------------------
# Знак > означает непосредственного ребёнка.
#
# .question > h2 означает:
# найти <h2>, который является непосредственным ребёнком
# блока .question.
# ------------------------------------------------------------

example_html |>
  html_element(".question > h2") |>
  html_text2()


# ------------------------------------------------------------
# 8. АТРИБУТЫ HTML
#
# Текст ссылки и адрес ссылки — разные вещи.
#
# В элементе
#
# <a href="sth2006.html">Quaestiones 6-21</a>
#
# Quaestiones 6-21 — текст элемента;
# sth2006.html — значение атрибута href.
#
# html_attr() извлекает значение указанного атрибута.
# ------------------------------------------------------------

next_link <- example_html |>
  html_element("a.next")

next_link


# Текст ссылки.
next_link |>
  html_text2()


# Адрес ссылки.
next_link |>
  html_attr("href")


