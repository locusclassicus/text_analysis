read_summa <- function(url) {
   
  Sys.sleep(5)
  
  summa_html <- read_html(url)
  
  paragraphs <- summa_html |>
    html_elements("p[title]")
  
  labels <- paragraphs |>
    html_attr("title")
  
  ids <- paragraphs |>
    html_element("a") |>
    html_attr("name")
  
  texts <- paragraphs |>
    html_text2()
  
  refs <- paragraphs |>
    html_element(".ref") |>
    html_text2()
  
  texts_clean <- str_remove(
    texts,
    fixed(refs)
  ) |>
    str_squish()
  
  summa_tbl <- tibble(
    stable_id = ids,
    label = labels,
    text = texts_clean
  )
  
  summa_tbl
}

