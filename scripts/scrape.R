      str_detect(
        label,
        "q\\.\\s+\\d+\\s+pr\\.$"
      ) ~ "prooemium",
      
      str_detect(
        label,
        "a\\.\\s+\\d+\\s+arg\\.\\s+\\d+$"
      ) ~ "argumentum",
      
      str_detect(
        label,
        "a\\.\\s+\\d+\\s+s\\.\\s*c\\.$"
      ) ~ "sed contra",
      
      str_detect(
        label,
        "a\\.\\s+\\d+\\s+co\\.$"
      ) ~ "respondeo",
      
      str_detect(
        label,
        "a\\.\\s+\\d+\\s+ad\\s+\\d+$"
      ) ~ "responsio"
      
    ),
    
    number = case_when(
      
      type == "argumentum" ~
        as.integer(
          str_match(
            label,
            "arg\\.\\s+(\\d+)"
          )[, 2]
        ),
      
      type == "responsio" ~
        as.integer(
          str_match(
            label,
            "ad\\s+(\\d+)"
          )[, 2]
        ),
      
      TRUE ~ NA_integer_
      
    )
  ) |>
  select(
    stable_id,
    question,
    article,
    type,
    number,
    text
  )

