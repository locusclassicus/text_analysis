library(tidyverse)
# library(ThemePark)
starwars <- starwars

# ------------------------------------------------------------
# СТОЛБЧАТАЯ ДИАГРАММА (Bar chart)
#
# Используется, когда нужно сравнить количество объектов
# в разных категориях.
#
# В этом примере считаем, сколько персонажей относится
# к каждому гендеру.
#
# aes() связывает переменные из таблицы с элементами графика.
#
# Здесь: x = gender означает, 
# что категории переменной gender будут расположены
# по горизонтальной оси.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(gender)) +
  geom_bar()

# ------------------------------------------------------------
# Добавляем подписи.
#
# labs() используется практически для любого графика.
# Он позволяет добавить заголовок, подписи осей
# и другие текстовые элементы.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = gender)) +
  geom_bar() +
  labs(
    title = "Количество персонажей",
    subtitle = "Да пребудет с нами сила!",
    x = "Гендер",
    y = "Количество"
  )

# ------------------------------------------------------------
# Меняем внешний вид столбцов и тему.
#
# fill  — цвет заливки;
# color — цвет контура.
#
# Эти параметры записаны НЕ внутри aes(),
# потому что один и тот же цвет применяется
# ко всем столбцам.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = gender)) +
  geom_bar(
    fill = "#8B008B",
    color = "grey40"
  ) +
  theme_minimal()

# ------------------------------------------------------------
# Цвет тоже может зависеть от данных.
#
# Теперь fill находится внутри aes().
# Это означает, что цвет определяется
# значениями переменной sex. 
#
# Также поменяем позицию столбиков.
# Такой график удобно использовать,
# когда важно сравнить состав групп,
# а не их абсолютный размер.
# ------------------------------------------------------------

starwars |> 
  drop_na(gender) |> 
  ggplot(aes(x = gender, fill = sex)) +
  geom_bar() # попробуйте также dodge

# ------------------------------------------------------------
# ДИАГРАММА РАССЕЯНИЯ (Scatter plot)
#
# Когда использовать:
# Исследование связи между двумя количественными переменными.
#
# Обязательные эстетики:
# x, y
#
# Что показывает пример:
# Связь между ростом и массой персонажей.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = height, y = mass)) +
  geom_point()

# ------------------------------------------------------------
# Эстетика size контролирует размер точки
# Ее также можно привязать к переменной.
#
# Важное замечание.
# Для точек обычно используется эстетика color.
#
# Эстетика fill применяется к геометриям,
# которые имеют внутреннюю область
# (например, столбики или некоторые виды точек).
# Эстетика alpha контролирует прозрачность объекта.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = height, y = mass, color = gender)) +
  geom_point(size = 2,
             alpha = 0.5) +
  theme_bw()

# ------------------------------------------------------------
# coord_cartesian() позволяет приблизить область графика,
# не удаляя наблюдения из данных.
#
# Используем встроенные палитры, чтобы поменять цвет точек
# 
# Избавимся от NA
# ------------------------------------------------------------

starwars <- starwars |> 
  mutate(
    gender = replace_na(gender, "unknown")
    ) 

starwars |> 
  ggplot(aes(
    x = height,
    y = mass,
    color = gender
    )) +
  geom_point() +
  coord_cartesian(
    xlim = c(50, 250),
    ylim = c(0, 200)
    ) +
  scale_color_brewer(
    palette = "Set2",
    name = "Гендер") +
  labs(x = "Рост", y = "Вес") +
  theme_light()

# ------------------------------------------------------------
# scale_color_brewer()
#
# palette — название цветовой палитры.
#
# name — заголовок легенды.
#
# Аналогично работают:
#
# scale_fill_brewer()   — для заливки;
# scale_color_manual()  — если нужно
#                         задать свои цвета;
# scale_fill_manual()   — свои цвета заливки.
# ------------------------------------------------------------

# ------------------------------------------------------------
# ЯЩИК С УСАМИ (Boxplot)
#
# Когда использовать:
# Сравнение распределений количественной переменной
# между несколькими группами.
#
# Обязательные эстетики:
# x — категориальная переменная;
# y — количественная переменная.
#
# Что показывает пример:
# Распределение роста персонажей разных полов.
# ------------------------------------------------------------

# Перед тем как строить boxplot, важно понять,
# что такое квартили (подсказка: это частный случай квантилей).
#
# Представьте, что мы расположили всех персонажей
# по росту — от самого низкого до самого высокого.
#
# Затем разделили этот список на четыре равные части.
#
# Получаются три "границы":
#
# Q1 (первый квартиль)  — 25% наблюдений ниже этой точки.
# Q2 (второй квартиль)  — медиана, то есть середина данных.
# Q3 (третий квартиль)  — 75% наблюдений ниже этой точки.
#
# Таким образом:
#
# 25% | 25% | 25% | 25%
#
# Q1     Q2     Q3

quantile(1:100)

# Почему тут дроби? Квартиль не обязан совпадать с одним из наблюдений. 
# В R он вычисляется интерполяцией между соседними значениями.
# В нашем случае медиана лежит между 50-м и 51-м элементами


starwars |> 
  drop_na(sex) |> 
  filter(sex != "hermaphroditic") |> 
  ggplot(aes(x = sex, y = height)) +
  geom_boxplot()

# ------------------------------------------------------------
# Как читать boxplot?
#
# Линия внутри ящика — медиана
# (середина распределения).
#
# Нижняя граница ящика — первый квартиль (Q1).
#
# Верхняя граница ящика — третий квартиль (Q3).
#
# Сам ящик содержит центральные 50% наблюдений.
#
# "Усы" показывают диапазон типичных значений.
#
# Отдельные точки за пределами усов —
# возможные выбросы.
# ------------------------------------------------------------

# ------------------------------------------------------------
# Цвет может зависеть от категории.
#
# Здесь каждая группа получает собственный цвет.
# Также настраиваем толщину линии и размер выбросов.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(
  x = gender,
  y = height,
  fill = gender
)) +
  geom_boxplot(color = "grey30", 
               linewidth = 0.3,
               outlier.size = 0.8) +
  scale_fill_brewer(palette = "Set1") +
  theme_light() + 
  coord_flip() 
  

# ------------------------------------------------------------
# Как читать boxplot?
#
# Boxplot — это краткое описание распределения данных.
#
# Линия внутри ящика — медиана.
# Она делит наблюдения пополам:
# у 50% объектов значение меньше медианы,
# у 50% — больше.
#
# Нижняя граница ящика — первый квартиль (Q1).
# Верхняя граница — третий квартиль (Q3).
#
# Ящик содержит центральные 50% наблюдений.
#
# Чем выше ящик,
# тем сильнее различаются значения
# внутри основной массы данных.
#
# Расстояние между Q1 и Q3 называется
# межквартильным размахом (IQR).
#
# "Усы" показывают диапазон типичных значений.
# Они не обязательно доходят до минимума
# и максимума.
#
# Если наблюдение находится слишком далеко
# от основной массы данных,
# оно отображается отдельной точкой.
#
# Такие точки называют возможными выбросами.
# Они не всегда являются ошибками измерения,
# но требуют дополнительного внимания.
#
# ------------------------------------------------------------


# ------------------------------------------------------------
# В переменной species очень много различных видов.
# Если построить график для всех категорий,
# он получится слишком перегруженным.
#
# Функция fct_lump_n() оставляет только n самых
# часто встречающихся категорий.
#
# Все остальные категории объединяются
# в одну группу "Other".
# ------------------------------------------------------------

starwars_species <- starwars  |> 
  filter(
    !is.na(species),
    !is.na(height)
  )  |> 
  mutate(
    species = forcats::fct_lump_n(species, n = 3)
  )

# ------------------------------------------------------------
# geom_jitter()
#
# Добавляет отдельные наблюдения.
#
# Точки немного "раздвигаются" по горизонтали,
# чтобы не накладываться друг на друга.
#
# Благодаря этому можно увидеть,
# сколько наблюдений находится в каждой группе
# и где расположены отдельные значения.
# ------------------------------------------------------------

starwars_species |> 
  ggplot(aes(x = species, y = height, color = species)) +
  geom_boxplot(show.legend = FALSE) +
  geom_jitter(
    width = 0.2,
    alpha = 0.6,
    show.legend = FALSE
  ) +
  theme_light() +
  labs(x = NULL, y = "Рост")


# ------------------------------------------------------------
# Boxplot НЕ показывает форму распределения.
# Например, по нему нельзя понять,
# имеет ли распределение один пик
# или несколько.
# Что такое распределение?
#
# Распределение показывает,
# как часто встречаются различные значения
# количественной переменной.
#
# Например:
#
# • много ли персонажей среднего роста;
# • встречаются ли очень высокие персонажи;
# • есть ли несколько "скоплений" значений.
#
# Boxplot отвечает на эти вопросы кратко.
#
# Если же мы хотим увидеть само распределение,
# лучше использовать гистограмму.
# 
# ГИСТОГРАММА (Histogram)
#
# Когда использовать:
# Исследование распределения
# одной количественной переменной.
#
# Гистограмма подходит для непрерывных
# (или почти непрерывных) данных:
# рост, вес, возраст, доход и т.д.
#
# Для категориальных данных
# используется столбчатая диаграмма.
#
# Обязательные эстетики:
# x
#
# Что показывает пример:
# Распределение роста персонажей.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = height)) +
  geom_histogram(binwidth = 10, alpha = 0.5)

# ------------------------------------------------------------
# Как читать гистограмму?
#
# По горизонтальной оси располагаются значения
# переменной (например, рост).
#
# По вертикальной оси —
# количество наблюдений.
#
# Каждый столбик показывает,
# сколько наблюдений попало
# в определённый диапазон значений.

# ------------------------------------------------------------
# Важное различие.
#
# Столбчатая диаграмма:
# один столбец = одна категория.
#
# Гистограмма:
# один столбец = один диапазон числовых значений.

# ------------------------------------------------------------
# ДИАГРАММА ПЛОТНОСТИ (Density plot)
#
# Когда использовать:
# Исследование распределения одной количественной
# непрерывной переменной.
#
# Обязательная эстетика:
# x
#
# Что показывает пример:
# Распределение роста персонажей.
#
# Диаграмма плотности похожа на сглаженную гистограмму.
# Вместо отдельных столбиков мы видим плавную кривую.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = height)) +
  geom_density()

# ------------------------------------------------------------
# Как читать диаграмму плотности?
#
# По оси X располагаются значения переменной — рост.
#
# Чем выше кривая, тем чаще значения встречаются
# в этой области.
#
# Пики показывают области, где наблюдений много.
#
# Низкие участки показывают области,
# где наблюдений мало.
#
# Важно:
# по оси Y здесь не количество персонажей,
# а плотность распределения.
#
# Поэтому высоту кривой нельзя читать
# как непосредственное число наблюдений.

# ------------------------------------------------------------
# Сравниваем распределения нескольких групп.
#
# Эстетика color связывает цвет линии
# с категориальной переменной gender.
#
# alpha задаёт прозрачность.
# Он находится вне aes(), поэтому одинаков
# для всех групп.
# ------------------------------------------------------------

starwars |> 
  ggplot(aes(x = height, color = gender, fill = gender)) +
  geom_density(
    linewidth = 0.7,
    alpha = 0.3
  ) +
  theme_light() 



# ------------------------------------------------------------
# СКРИПИЧНАЯ ДИАГРАММА (Violin plot)
#
# Когда использовать:
# Сравнение распределений количественной переменной
# между несколькими категориями.
#
# Обязательные эстетики:
# x — категориальная переменная;
# y — количественная переменная.
#
# Что показывает пример:
# Распределение роста персонажей разных гендеров
#
# Скрипичная диаграмма сочетает идеи
# boxplot и диаграммы плотности.
# ------------------------------------------------------------

starwars |> 
  filter(mass < 200) |> 
  ggplot(aes(
    x = gender,
    y = mass
)) +
  geom_violin() +
  theme_light()

# ------------------------------------------------------------
# Как читать скрипичную диаграмму?
#
# Высота скрипки показывает диапазон значений.
#
# Ширина показывает, насколько часто значения
# встречаются в определённой области.
#
# Чем шире скрипка,
# тем больше наблюдений находится рядом
# с этим значением.
#
# В отличие от boxplot, скрипка показывает
# форму распределения.
#
# Но она не показывает медиану
# и квартили (можно совместить с ящиком при желании).
# ------------------------------------------------------------

# ЛИНЕЙНЫЙ ГРАФИК (Line chart)
#
# Когда использовать:
# Изображение изменений показателя
# вдоль упорядоченной оси.
#
# Чаще всего по оси X находится время.
#
# Обязательные эстетики:
# x, y
#
# Что показывает пример:
# Как меняется средний рост персонажей
# в зависимости от года рождения.
#
# Важно:
# линейный график имеет смысл только тогда,
# когда порядок значений по оси X содержателен.
# ------------------------------------------------------------

starwars_birth_year <- starwars  |> 
  filter(
    !is.na(birth_year),
    !is.na(height),
    species == "Human"
  )  |> 
  group_by(birth_year)  |> 
  summarise(
    mean_height = mean(height)
    )  |> 
  arrange(birth_year)

starwars_birth_year

# ------------------------------------------------------------
# geom_line() соединяет соседние наблюдения линией.
#
# x = birth_year — упорядоченная переменная;
# y = mean_height — средний рост.
#
# geom_point() добавляет сами наблюдаемые точки,
# чтобы было видно, где именно есть данные.
# ------------------------------------------------------------

starwars_birth_year |> 
  ggplot(aes(x = birth_year, y = mean_height)) +
  geom_line() +
  geom_point()

# ------------------------------------------------------------
# Осторожно с интерпретацией.
#
# В датасете starwars birth_year —
# не обычная календарная дата,
# а год рождения персонажа во вселенной Star Wars.
#
# Кроме того, для некоторых годов
# может быть только один персонаж.
#
# Поэтому этот график используется прежде всего
# для демонстрации устройства линейного графика,
# а не для содержательного вывода о тенденции.
# ------------------------------------------------------------

# ------------------------------------------------------------
# ФАСЕТЫ (facet_wrap)
#
# Когда использовать:
# Когда нужно построить один и тот же график
# отдельно для нескольких групп.
#
# facet_wrap() не создаёт новый тип графика.
# Он разбивает уже знакомый график
# на несколько небольших панелей.
#
# Что показывает пример:
# Распределение роста отдельно
# для разных значений переменной gender.
# 
# Спрячем легенду и повернем подписи
# ------------------------------------------------------------

starwars |> 
  filter(gender != "unknown") |> 
  ggplot(aes(x = height, fill = gender)) +
  geom_histogram(bins = 15, show.legend = FALSE) +
  facet_wrap(~ gender, scales = "free") +
  coord_cartesian(xlim = c(50, 250)) +
  theme_light() +
  theme(axis.text.x = element_text(angle = 45))

# ------------------------------------------------------------
# Как читать фасеты?
#
# Во всех панелях используются одинаковые:
# - переменные;
# - тип графика;
# - шкалы осей.
#
# Отличается только группа наблюдений.
#
# Это позволяет сравнивать распределения
# между группами.
#
# Формула ~ gender означает:
# создать отдельную панель
# для каждого значения gender.
# ------------------------------------------------------------

# ------------------------------------------------------------
# facet_wrap() можно применять
# практически к любому графику.
#
# Здесь мы сравниваем связь между ростом и массой
# отдельно для разных групп.
# ------------------------------------------------------------

ggplot(starwars, aes(
  x = height,
  y = mass,
  color = gender
)) +
  geom_point(show.legend = FALSE) +
  facet_wrap(~ gender) +
  coord_cartesian(
    xlim = c(50, 250),
    ylim = c(0, 200)
  ) + 
  theme_light() +
  theme(axis.text.x = element_text(angle = 45))

# ------------------------------------------------------------
# LIST-COLUMNS
#
# Обычно в одной ячейке таблицы хранится
# одно значение.
#
# Но в starwars есть столбцы,
# где одна ячейка содержит целый вектор.
#
# Например:
# - films — фильмы с участием персонажа;
# - vehicles — транспортные средства;
# - starships — космические корабли.
#
# Такие столбцы называются list-columns.
# ------------------------------------------------------------

glimpse(starwars)

# ------------------------------------------------------------
# ТАЙДИФИКАЦИЯ СТОЛБЦА films
#
# Сейчас один персонаж занимает одну строку,
# а все его фильмы находятся внутри одной ячейки.
#
# Для анализа нам удобнее правило:
#
# одна строка = один персонаж в одном фильме.
#
# unnest_longer() распаковывает вектор
# и создаёт отдельную строку
# для каждого его элемента.
# ------------------------------------------------------------

starwars_films <- starwars  |> 
  select(
    name,
    gender,
    species,
    films, 
    homeworld
  )  |> 
  unnest_longer(films)

starwars_films

# ------------------------------------------------------------
# После unnest_longer():
#
# если персонаж участвовал в пяти фильмах,
# он будет занимать пять строк.
#
# Остальные значения строки
# автоматически повторяются.
# ------------------------------------------------------------

starwars_films  |> 
  filter(name == "Luke Skywalker")

# ------------------------------------------------------------
# Сколько персонажей представлено
# в каждом фильме?
#
# count(films) группирует строки по фильмам
# и считает число строк в каждой группе.
#
# После распаковки одна строка соответствует
# одному персонажу в одном фильме.
# ------------------------------------------------------------

film_counts <- starwars_films  |> 
  count(
    films,
    sort = TRUE
  )

film_counts

# ------------------------------------------------------------
# Строим столбчатую диаграмму
# по уже рассчитанным значениям.
#
# Поэтому используется geom_col(),
# а не geom_bar().
#
# geom_bar() сам считает строки.
# geom_col() использует готовую переменную n.
# ------------------------------------------------------------

film_counts |> 
  ggplot(aes(x = reorder(films, -n), y = n, fill = films)) +
  geom_col(show.legend = FALSE) +
  labs(
    title = "Количество персонажей в фильмах Star Wars",
    x = "Количество персонажей",
    y = "Фильм"
  ) +
  theme_light() +
  coord_flip() +
  scale_fill_viridis_d() 

# ------------------------------------------------------------
# Сравним количество персонажей разных видов
# в каждом фильме.
#
# Сначала считаем число наблюдений
# для каждой комбинации:
# фильм + gender.
# ------------------------------------------------------------

species_films_counts <- starwars_films  |> 
  filter(!is.na(species))  |> 
  count(species, films) |> 
  mutate(species = fct_lump_n(species, n = 3))

species_films_counts

# ------------------------------------------------------------
# Для каждого значения species
# создаётся отдельная панель.
#
# Во всех панелях показаны те же фильмы,
# поэтому их удобно сравнивать.
# 
# Обратите внимание на поворот всего графика
# ------------------------------------------------------------

species_films_counts |> 
  filter(films != "A New Hope") |> 
  ggplot(aes(x = species, y = n, fill = species)) +
  geom_col(show.legend = FALSE) +
  facet_wrap(~ films, scales = "free_y", nrow = 4) +
  coord_flip() +
  theme_light()

# ------------------------------------------------------------
# Как читать этот график?
#
# Каждая панель соответствует одному фильму.
#
# По горизонтальной оси показано
# количество персонажей каждого вида.
#
# Во всех фильмах преобладают люди (Human).
#
# Категория Other объединяет редкие виды,
# поэтому особенно велика в фильмах,
# где представлено большее разнообразие
# персонажей.
#
# Благодаря facet_wrap() можно легко
# сравнить состав персонажей
# между разными фильмами.
# ------------------------------------------------------------

# ------------------------------------------------------------
# ТАЙДИФИКАЦИЯ СТОЛБЦА vehicles
#
# Одна ячейка может содержать несколько
# транспортных средств персонажа.
#
# После unnest_longer() одна строка будет означать:
#
# один персонаж + одно транспортное средство.
# ------------------------------------------------------------

starwars_vehicles <- starwars  |> 
  select(
    name,
    gender,
    species,
    vehicles
  )  |> 
  unnest_longer(vehicles)

starwars_vehicles

# ------------------------------------------------------------
# У некоторых персонажей список vehicles пустой.
#
# После распаковки такие наблюдения
# могут отсутствовать в полученной таблице.
#
# Считаем, сколько персонажей связано
# с каждым транспортным средством.
# ------------------------------------------------------------

vehicle_counts <- starwars_vehicles  |> 
  count(
    vehicles,
    sort = TRUE
  )

vehicle_counts


# ------------------------------------------------------------
# Точно так же можно распаковать starships.
#
# Одна строка после распаковки:
# один персонаж + один космический корабль.
# ------------------------------------------------------------

starwars_starships <- starwars  |> 
  select(
    name,
    gender,
    species,
    starships
  )  |> 
  unnest_longer(starships)

# Считаем персонажей для каждого корабля.

starship_counts <- starwars_starships  |> 
  count(
    starships,
