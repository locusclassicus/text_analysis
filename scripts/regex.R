# 12. МАЛЕНЬКОЕ ИССЛЕДОВАНИЕ:
#     ГДЕ В РОМАНЕ ДАРСИ?
# ------------------------------------------------------------

# Посчитаем, сколько раз Darcy упоминается
# в каждом предложении.
#
# "(Mr )?Darcy" означает:
#
#   Darcy
#   ИЛИ
#   Mr Darcy
#
# Но поскольку "Darcy" входит и в "Mr Darcy",
# для простого подсчёта достаточно было бы искать "Darcy".
#
# Здесь мы оставляем конструкцию с ? как учебный пример.

darcy_tbl <- pp_tbl |>
  mutate(
    n = str_count(text, "(Mr )?Darcy")
  ) |>
  group_by(chapter_nr) |>
  summarise(
    Darcy = sum(n),
    .groups = "drop"
  )

darcy_tbl


# То же самое для Elizabeth.

liz_tbl <- pp_tbl |>
  mutate(
    n = str_count(text, "Elizabeth|Lizzy")
  ) |>
  group_by(chapter_nr) |>
  summarise(
    Elizabeth = sum(n),
    .groups = "drop"
  )

liz_tbl


# Соединим таблицы.

characters_tbl <- darcy_tbl |>
  left_join(liz_tbl, by = "chapter_nr")

characters_tbl


# Переведём данные в длинный формат для ggplot.

characters_long <- characters_tbl |>
  pivot_longer(
    cols = c(Darcy, Elizabeth),
    names_to = "character",
    values_to = "mentions"
  )


# И наконец визуализация:
