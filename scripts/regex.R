# ------------------------------------------------------------
# 6. КВАНТИФИКАТОРЫ: СКОЛЬКО РАЗ?
# ------------------------------------------------------------

# Основные квантификаторы:
#
#   ?       0 или 1 раз
#   *       0 или больше раз
#   +       1 или больше раз
#   {n}     ровно n раз
#   {m,n}   от m до n раз
#
# Квантификатор относится к элементу,
# который стоит непосредственно перед ним.


x <- c(
  "Chapter 1",
  "Chapter 12",
  "Chapter 123",
  "Chapter X"
)

str_view(x, "Chapter \\d")
str_view(x, "Chapter \\d+")
str_view(x, "Chapter \\d{2}")


# Очень полезный пример: необязательная часть.
#
# В тексте персонаж может называться:
#
#   Darcy
#   Mr Darcy
#
# Скобки группируют несколько символов в единый блок.
# ? после группы означает: группа может встретиться 0 или 1 раз.

names_demo <- c(
  "Darcy entered the room.",
  "Mr Darcy entered the room.",
  "Mr. Darcy entered the room.",
  "Elizabeth saw Darcy.",
  "Mrs Darcy"
)

str_view(names_demo, "(Mr )?Darcy")
# сравните:
str_view(names_demo, "(Mr\\.? )?Darcy")

# ------------------------------------------------------------
# 7. "ИЛИ" И ГРУППЫ
# ------------------------------------------------------------

# Вертикальная черта означает "или":
#
#   Mr|Mrs
#
# Скобки показывают границы альтернатив:
#
#   (Mr|Mrs)\\.
#
# Найдём два типа сокращений одновременно.

dialogue <- '"My dear Mr. Bennet," said his lady to him one day, "have you heard that Netherfield Park is let at last?" Mr. Bennet replied that he had not. "But it is," returned she; "for Mrs. Long has just been here, and she told me all about it."'

str_view(dialogue, "(Mr|Mrs)\\.")


# ------------------------------------------------------------
# 8. ИЗВЛЕЧЬ, А НЕ ТОЛЬКО НАЙТИ
# ------------------------------------------------------------

# str_detect() сообщает, есть ли совпадение.
# str_extract() возвращает само совпадение.
#
# str_extract() возвращает ПЕРВОЕ совпадение.
# str_extract_all() возвращает ВСЕ совпадения.

str_extract(dialogue, "(Mr|Mrs)\\.")

str_extract_all(dialogue, "(Mr|Mrs)\\.")


# Обратите внимание:
# str_extract_all() возвращает список.
#
# Для одной строки удобно взять его первый элемент:

str_extract_all(dialogue, "(Mr|Mrs)\\.")[[1]]


# ------------------------------------------------------------
# 9. ЗАМЕНА
# ------------------------------------------------------------

# str_replace() заменяет первое совпадение.
# str_replace_all() заменяет все совпадения.

str_replace(dialogue, "Mr\\.", "Mr")

str_replace_all(dialogue, "Mr\\.", "Mr")


# Но нам надо обработать и Mr., и Mrs.
#
# Можно убрать точку после обоих сокращений.
#
# В шаблоне:
#
#   (Mr|Mrs)\\.
#
# первая группа — это Mr или Mrs.
#
# В строке замены:
#
#   "\\1"
#
# означает:
# "вставь сюда текст, который совпал с первой группой".
#
# Такие ссылки называются backreferences.

dialogue_clean <- str_replace_all(
  dialogue,
  "(Mr|Mrs)(\\.)",
  "\\1"
)

dialogue_clean


# Теперь попробуем снова разделить диалог на предложения.

str_split_1(dialogue_clean, boundary("sentence"))


# Получилось лучше:
