pp_tbl


# ------------------------------------------------------------
# 11. НОМЕРА ГЛАВ
# ------------------------------------------------------------

# В тексте остались заголовки вида:
#
#   Chapter 1
#   Chapter 2
#   ...
#
# Найдём предложения, содержащие такие заголовки.

pp_tbl |>
  filter(str_detect(text, "Chapter \\d+")) 


# str_detect() возвращает TRUE там, где встретился заголовок.
#
# cumsum() считает накопительную сумму:
#
# FALSE FALSE TRUE FALSE FALSE TRUE ...
#   0     0    1    1     1    2 ...
#
# Благодаря этому можно получить номер текущей главы.

pp_tbl <- pp_tbl |>
  mutate(
    chapter_nr = cumsum(str_detect(text, "Chapter \\d+"))
  )


# Сам заголовок Chapter ... теперь можно удалить из текста.

pp_tbl <- pp_tbl |>
  mutate(
    text = str_remove(text, "Chapter \\d+"),
    text = str_remove(text, "PRIDE AND PREJUDICE By Jane Austen"),
    text = str_squish(text),
    text = str_remove_all(text, "_")
  )


# Посмотрим результат.

pp_tbl |>
  select(chapter_nr, text) |>
  head(10)

