# На первый взгляд всё работает.
# Но в регулярных выражениях точка имеет специальное значение:
#
#   .   = любой один символ
#
# Поэтому шаблон "Mr." означает:
#
#   M + r + любой символ
#
# Например:

test <- c("Mr.", "Mrs.", "Mra", "Mr7", "Mr!")

str_detect(test, "Mr.")


# Если нам нужна БУКВАЛЬНАЯ точка, её надо экранировать.
#
# В самом регулярном выражении буквальная точка выглядит так:
#
#   \.
#
# Но регулярное выражение мы записываем внутри строки R,
# а обратная косая черта имеет специальное значение и в строках R.
#
# Поэтому в коде приходится писать две:
#
#   "\\."

str_detect(test, "Mr\\.")


# Это один из самых неприятных моментов regex.
# Полезно помнить:
#
#   regex, который мы хотим:  \.
#   строка, которую пишем в R: "\\."


# ------------------------------------------------------------
# 5. КЛАССЫ СИМВОЛОВ
# ------------------------------------------------------------

# Иногда нам нужен не конкретный символ,
# а символ определённого типа.
#
# Частые классы:
#
#   \\d   цифра
#   \\s   пробельный символ
#   \\w   "символ слова": буква, цифра и некоторые служебные знаки
#


demo <- c(
  "Chapter 1",
  "chapter 12",
  "Room A",
  "2026",
  "Mr. Darcy"
)

str_view(demo, "\\d")


# Квантификатор + означает:
#
#   "предыдущий элемент встречается один или больше раз"
#
# Поэтому:
#
#   \\d+ = одна или несколько цифр

str_view(demo, "\\d+")


# Теперь мы можем описать номер главы:

str_view(demo, "Chapter +\\d+")


# Квадратные скобки позволяют задать собственный класс:
#
#   [abc]    один символ: a, b или c
#   [0-9]    одна цифра
#   [A-Z]    одна английская прописная буква
#
# Например, эти два шаблона для номеров глав здесь эквивалентны:

str_view(demo, "Chapter \\d+")
str_view(demo, "Chapter [0-9]+")


