# ------------------------------------------------------------
# 15. ЧТО НУЖНО ЗАПОМНИТЬ
# ------------------------------------------------------------
#
# Не нужно запоминать весь язык регулярных выражений.
#
# Достаточно понимать принцип:
#
#   обычный текст       "Darcy"
#   любой символ        .
#   цифра               \\d
#   один из символов    [abc]
#   отрицание класса    [^abc]
#   один или больше     +
#   ноль или один       ?
#   группа              (...)
#   или                  |
#   начало строки       ^
#   конец строки        $
#   буквальная точка    \\.
#
# И несколько основных функций stringr:
#
#   str_detect()       есть ли совпадение?
#   str_subset()       какие строки совпали?
#   str_count()        сколько совпадений?
#   str_extract()      что именно совпало?
#   str_extract_all()  все совпадения
#   str_replace_all()  заменить совпадения
#   str_remove()       удалить совпадение
#   str_split_1()      разделить одну строку
#
# Главное правило при работе с regex:
#
#   сначала проверьте шаблон на маленьком примере,
#   и только потом применяйте его ко всему корпусу.
#
# ============================================================
