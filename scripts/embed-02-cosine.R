# 5. СРАВНИВАЕМ НАШИ ЧЕТЫРЕ ФРАЗЫ -----------------------------
# В каждой строке сохраняем полный вектор одного текста.
# list() позволяет хранить несколько чисел в одной ячейке.
# Получаются два столбца-списка: частоты и веса TF-IDF.
text_vectors <- weights |>
  arrange(id, word) |>
  summarise(
    count_vector = list(n),
    tfidf_vector = list(tf_idf),
    .by = id
  )

text_vectors

# Фраза A — точка сравнения.
# pull() извлекает столбец; pluck(1) — первый элемент списка.
reference_counts <- text_vectors |>
  filter(id == "A") |>
  pull(count_vector) |>
  pluck(1)

reference_tfidf <- text_vectors |>
  filter(id == "A") |>
  pull(tfidf_vector) |>
  pluck(1)

# map_dbl() применяет нашу функцию к каждому вектору.
# Для каждой строки получается ровно одно число.
lexical_scores <- text_vectors |>
  mutate(
    count_cosine = map_dbl(
      count_vector, cosine_similarity, y = reference_counts
    ),
    tfidf_cosine = map_dbl(
      tfidf_vector, cosine_similarity, y = reference_tfidf
    )
  ) |>
  select(id, count_cosine, tfidf_cosine) |>
  left_join(texts, by = "id") |>
  filter(id != "A")

lexical_scores |>
  arrange(desc(count_cosine))

lexical_scores |>
  arrange(desc(tfidf_cosine))

