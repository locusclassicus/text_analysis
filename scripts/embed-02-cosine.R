library(tidyverse)

# 1. ДВА МАЛЕНЬКИХ ВЕКТОРА ------------------------------------
# Это условные числа для объяснения формулы, не результат модели.
# B вдвое длиннее A, но соотношение его координат такое же.
example <- tibble(
  coordinate = c("первая", "вторая"),
  a = c(4, 1),
  b = c(8, 2)
)

example

# 2. ЧИСЛИТЕЛЬ: СКАЛЯРНОЕ ПРОИЗВЕДЕНИЕ ------------------------
# Перемножаем соответствующие координаты, затем складываем.
# Для примера: 4 * 8 + 1 * 2 = 34.
calculation <- example |>
  mutate(
    product = a * b,
    a_squared = a^2,
    b_squared = b^2
  )

calculation

# 3. ЗНАМЕНАТЕЛЬ: ДЛИНЫ ВЕКТОРОВ ------------------------------
# Длина A = sqrt(4^2 + 1^2) = sqrt(17).
# Длина B = sqrt(8^2 + 2^2) = sqrt(68).
# sqrt() — квадратный корень.
calculation |>
  summarise(
    dot_product = sum(product),
    length_a = sqrt(sum(a_squared)),
    length_b = sqrt(sum(b_squared))
  ) |>
  mutate(cosine = dot_product / (length_a * length_b))

# Получилось 1: направления совпадают.
# Мы сравниваем направление, поэтому удвоение всех частот
# не делает два вектора менее похожими.
#
# Косинус лежит между -1 и 1:
#  1 — одинаковое направление;
#  0 — перпендикулярные направления;
# -1 — противоположные направления.
#
# У частотных векторов нет отрицательных координат,
# поэтому их косинус лежит между 0 и 1.
# У эмбеддингов отрицательные координаты возможны.
#
# Геометрическое «противоположны» НЕ означает антонимию.
# Косинус 0.8 НЕ означает 80% одинакового смысла.
# Универсального порога «это точно подходящий текст» нет.
# Для нулевого вектора формула не определена.

# 4. ЗАПИСЫВАЕМ ЭТУ ЖЕ ФОРМУЛУ КАК ФУНКЦИЮ -------------------
# x и y — два числовых вектора одинаковой длины.
# Их координаты должны относиться к одним и тем же признакам.
# Эта функция пригодится и для частот, и для эмбеддингов.
cosine_similarity <- function(x, y) {
  sum(x * y) / (sqrt(sum(x^2)) * sqrt(sum(y^2)))
}

cosine_similarity(c(4, 1), c(8, 2))
cosine_similarity(c(4, 1), c(1, 4))

